#!/usr/bin/env python3
"""Gate: a human attestation is on record on GitHub (S1 critic K4).

Some claims rest on acts only the human can perform or observe (applying Supabase
migrations, reading production's schema). The attestation is a comment on a pull request
of Navigata1/storysynchq, written by the login Navigata1, whose first line is
`A2-ATTEST <NAME>` and which lists what is attested on the lines after it.

Provenance, stated plainly: the lead acts on GitHub with the operator's token, so it could
technically post as Navigata1. Two things stand against that: every comment the lead posts
carries the Claude Code footer (the GitHub connector appends it), and this gate rejects any
comment with that footer; and the contract forbids the lead from posting A2-ATTEST. The
second is discipline, not a check, so this gate is reported as advisory, never enforced.

Usage: python3 ops/mission/gates/hitl.py cloud-schema
       A2_HITL_COMMENTS=<file.json> python3 ... (fixtures: a JSON list of comments)
"""
import json
import os
import subprocess
import sys

REPO = "Navigata1/storysynchq"
HUMAN = "Navigata1"
FOOTER = "Generated by [Claude Code]"


def comments():
    fixture = os.environ.get("A2_HITL_COMMENTS")
    if fixture:
        with open(fixture) as f:
            return json.load(f)
    r = subprocess.run(["gh", "api", "--paginate", f"repos/{REPO}/issues/comments?per_page=100"],
                       capture_output=True, text=True)
    if r.returncode != 0:
        print(f"[FAIL] cannot read GitHub comments: {r.stderr.strip()[:200]}")
        sys.exit(1)
    out = []
    for chunk in r.stdout.replace("][", "]\n[").splitlines():
        if chunk.strip():
            out.extend(json.loads(chunk))
    return out


def main():
    if len(sys.argv) != 2:
        print("[FAIL] usage: hitl.py <NAME>")
        sys.exit(1)
    name = sys.argv[1]
    tag = f"A2-ATTEST {name}"
    found = []
    for c in comments():
        body = (c.get("body") or "").replace("\r\n", "\n")
        lines = body.split("\n")
        if lines[0].strip() != tag:
            continue
        if (c.get("user") or {}).get("login") != HUMAN:
            continue
        if FOOTER in body:
            print(f"[FAIL] {c.get('html_url', '?')} carries the Claude Code footer: the lead wrote it")
            sys.exit(1)
        statements = [l.strip() for l in lines[1:] if l.strip()]
        if statements:
            found.append((c, statements))
    if not found:
        print(f"[FAIL] no '{tag}' comment by {HUMAN} with statements (waiting on the operator)")
        sys.exit(1)
    c, statements = found[-1]
    print(f"[PASS] {tag} by {HUMAN} at {c.get('created_at')}: {len(statements)} statement(s) [advisory: provenance is discipline, see docstring]")


if __name__ == "__main__":
    main()
